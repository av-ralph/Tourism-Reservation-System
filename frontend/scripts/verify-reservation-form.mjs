import assert from 'node:assert/strict'
import {readFileSync,writeFileSync,mkdirSync} from 'node:fs'
import {unzipSync,strFromU8} from 'fflate'
import {fillReservationForm,reservationArea} from '../src/reservation-form.js'
const template=readFileSync(new URL('../public/documents/reservation-template.docx',import.meta.url))
const record={id:'test',createdAt:'2026-10-09T14:00:00Z',date:'2026-10-15',start:'09:00',end:'11:00',subject:'Food & Beverage',purpose:'Practice <plating> $&',facility:'Hot Kitchen',name:'Sample Student',email:'sample@example.com',studentId:'2026-001',instructor:'Sample Instructor',equipment:'2 | Mixing bowls\n4 | Measuring cups\nTray $& (quantity unspecified)'}
const original=unzipSync(template),result=unzipSync(fillReservationForm(template,record)),xml=strFromU8(result['word/document.xml'])
const templateXml=strFromU8(original['word/document.xml'])
const masthead=strFromU8(original['word/header2.xml'])
for(const line of ['Cristal e-College','Academic Division','Hospitality Management'])assert(masthead.includes(line),`masthead: ${line}`)
assert.equal((masthead.match(/<a:blip\b/g)||[]).length,2,'both logos appear in the masthead')
assert(masthead.includes('<w:gridCol w:w="1584"/><w:gridCol w:w="7416"/><w:gridCol w:w="1584"/>'),'masthead reserves a wide title column between the logos')
assert(masthead.includes('<w:jc w:val="left"/>'),'masthead title aligns beside the college seal')
assert(masthead.includes('<w:bottom w:val="single" w:sz="16" w:color="000000"/>'),'masthead has the reference underline')
for(const key of Object.keys(original)) if(key!=='word/document.xml') assert.deepEqual(result[key],original[key],key+' preserved')
assert(!xml.includes('{{'))
assert.equal((xml.match(/☒/g)||[]).length,1)
assert.equal((xml.match(/☐/g)||[]).length,9)
for(const marker of ['USAGE_DATE','USAGE_TIME','SUBJECT','PURPOSE','ITEM_QUANTITY','ITEM_DESCRIPTION','LAB_RELEASED','LAB_REMARKS','LAB_RETURNED','LAB_GOOD','LAB_LOST','LAB_DAMAGED']){
  const index=templateXml.indexOf(`{{${marker}}}`)
  assert(index>=0,marker)
  const paragraph=templateXml.slice(templateXml.lastIndexOf('<w:p',index),templateXml.indexOf('</w:p>',index))
  assert(paragraph.includes('<w:jc w:val="center"/>'),`${marker} centered`)
  assert(paragraph.includes('<w:b/>'),`${marker} bold`)
}
const areaLabels={BAR:'Bar Area',DINING:'Dining Area',FRONT_OFFICE:'Front Office Area',HOT_KITCHEN:'Hot Kitchen',COLD_KITCHEN:'Cold Kitchen',LAUNDRY:'Laundry Area',MINI_FUNCTION:'Mini Function Room',HARMONIA:'Harmonia Mini-Hotel Room',LUNARA:'Lunara Mini-Hotel Room',COMPUTER:'Computer Laboratory MH 302'}
for(const [facility,area] of [['Bar Area','BAR'],['Dining Area','DINING'],['Front Office Area','FRONT_OFFICE'],['Hot Kitchen','HOT_KITCHEN'],['Cold Kitchen','COLD_KITCHEN'],['Laundry Area','LAUNDRY'],['Harmonia Mini-Hotel','HARMONIA'],['Lunara Mini-Hotel','LUNARA'],['Mini Function Room','MINI_FUNCTION'],['Computer Laboratory MH 302','COMPUTER']]){
  assert.equal(reservationArea(facility),area)
  const filled=strFromU8(unzipSync(fillReservationForm(template,{...record,facility}))['word/document.xml'])
  assert.equal((filled.match(/☒/g)||[]).length,1,facility)
  assert(filled.slice(filled.indexOf('☒'),filled.indexOf('☒')+450).includes(areaLabels[area]),`${facility} checked area`)
  assert(filled.includes(facility),facility)
}
for(const text of ['Food &amp; Beverage','Practice &lt;plating&gt; $&amp;','Hot Kitchen','Sample Student','SAMPLE INSTRUCTOR','sample@example.com','2026-001','Mixing bowls','Measuring cups','Tray $&amp; (quantity unspecified)'])assert(xml.includes(text),text)
assert(templateXml.includes('Signature over printed name'))
assert.equal((xml.match(/<w:tr\b/g)||[]).length,(strFromU8(original['word/document.xml']).match(/<w:tr\b/g)||[]).length+11)
const long=fillReservationForm(template,{...record,studentId:'',equipment:Array.from({length:30},(_,i)=>`${i+1} | Item ${i+1}`).join('\n')})
const longXml=strFromU8(unzipSync(long)['word/document.xml'])
for(let i=1;i<=30;i++) assert(longXml.includes(`Item ${i}</w:t>`),`Item ${i} retained`)
assert.equal((longXml.match(/<w:tr\b/g)||[]).length,(templateXml.match(/<w:tr\b/g)||[]).length+29,'30 inventory rows are added')
const allItems=Array.from({length:379},(_,i)=>`${i+1} | Inventory item ${i+1}`)
const allItemsXml=strFromU8(unzipSync(fillReservationForm(template,{...record,equipment:allItems.join('\n')}))['word/document.xml'])
for(let i=1;i<=allItems.length;i++)assert(allItemsXml.includes(`Inventory item ${i}</w:t>`),`Inventory item ${i} retained`)
assert.equal((allItemsXml.match(/<w:tr\b/g)||[]).length,(templateXml.match(/<w:tr\b/g)||[]).length+allItems.length-1,'every selected item has a row')
assert(allItemsXml.includes('SAMPLE INSTRUCTOR'),'signer is retained after a long inventory list')
const structuredSelection=allItems.map((_,i)=>({id:`item-${i+1}`,quantity:i+1,name:`Inventory item ${i+1}`}))
const laboratoryRecord={...record,equipment:'None',inventorySelection:JSON.stringify([{id:'bowl',quantity:3,name:'Mixing bowls'},{id:'tray',quantity:2,name:'Service tray'}]),laboratoryEntries:JSON.stringify([{released:'2',remarks:'Checked & issued',returned:'2026-10-18',condition:'Good order'},{released:'1',remarks:'Handle marked',returned:'',condition:'Damaged'}])}
const laboratoryXml=strFromU8(unzipSync(fillReservationForm(template,laboratoryRecord))['word/document.xml'])
for(const text of ['Checked &amp; issued','Handle marked','Oct 18, 2026'])assert(laboratoryXml.includes(text),`laboratory value ${text}`)
assert.equal((laboratoryXml.match(/✓/g)||[]).length,2,'condition marks saved for both laboratory rows')
assert(!laboratoryXml.includes('{{LAB_'),'laboratory placeholders filled')
const structuredXml=strFromU8(unzipSync(fillReservationForm(template,{...record,equipment:'None',inventorySelection:JSON.stringify(structuredSelection)}))['word/document.xml'])
for(let i=1;i<=allItems.length;i++)assert(structuredXml.includes(`Inventory item ${i}</w:t>`),`Structured item ${i} retained`)
const generatedIds=[...structuredXml.matchAll(/w14:paraId="(F[0-9A-F]{7})"/g)].map(match=>match[1])
assert.equal(new Set(generatedIds).size,generatedIds.length,'generated rows have unique paragraph IDs')
const signed=unzipSync(fillReservationForm(template,{...record,instructorReviewedBy:'Actual Approver',instructorReviewedAt:'2026-10-14T16:30:00Z'},new Uint8Array([137,80,78,71])))
const signedXml=strFromU8(signed['word/document.xml'])
assert(signedXml.includes('ACTUAL APPROVER'))
assert(!signedXml.includes('SAMPLE INSTRUCTOR'))
assert(signedXml.indexOf('rIdInstructorSignature')<signedXml.indexOf('ACTUAL APPROVER'))
assert(!signedXml.includes('{{'))
assert(strFromU8(signed['word/_rels/document.xml.rels']).includes('media/instructor-signature.png'))
const fullySigned=unzipSync(fillReservationForm(template,{...record,instructorReviewedBy:'Actual Approver',instructorReviewedAt:'2026-10-14T16:30:00Z',adminReviewedBy:'Cristian Jay M. Pechon',adminReviewedAt:'2026-10-15T02:00:00Z'},new Uint8Array([137,80,78,71]),new Uint8Array([137,80,78,71,1])))
const fullySignedXml=strFromU8(fullySigned['word/document.xml'])
assert(fullySignedXml.includes('CRISTIAN JAY M. PECHON'))
assert(fullySignedXml.includes('rIdAdminSignature'))
assert(strFromU8(fullySigned['word/_rels/document.xml.rels']).includes('media/admin-signature.png'))
assert.deepEqual(fullySigned['word/media/admin-signature.png'],new Uint8Array([137,80,78,71,1]))
assert(!fullySignedXml.includes('{{'))
const waived=unzipSync(fillReservationForm(template,{...record,adminOverride:'true',adminOverrideReason:'Instructor unavailable',adminReviewedBy:'Cristian Jay M. Pechon',adminReviewedAt:'2026-10-15T02:00:00Z'},undefined,new Uint8Array([137,80,78,71,1])))
const waivedXml=strFromU8(waived['word/document.xml'])
assert(waivedXml.includes('INSTRUCTOR REVIEW WAIVED'))
assert(waivedXml.includes('Instructor review waived by administrator'))
assert(!waivedXml.includes('rIdInstructorSignature'))
assert(waivedXml.includes('rIdAdminSignature'))
assert.equal((xml.match(/<w:tblHeader\b/g)||[]).length,3)
const missingXml=strFromU8(unzipSync(fillReservationForm(template,{createdAt:'bad date',purpose:'A\u0000B'}))['word/document.xml'])
assert(!missingXml.includes('Invalid Date'))
assert(!missingXml.includes('undefined'))
assert(!missingXml.includes('\u0000'))
assert(missingXml.includes('AB'))
assert.throws(()=>fillReservationForm(new Uint8Array([1,2,3]),record))
const literalXml=strFromU8(unzipSync(fillReservationForm(template,{...record,subject:'Literal {{INSTRUCTOR}}',equipment:'1 | {{SIGNATURE}}'}))['word/document.xml'])
assert(literalXml.includes('Literal &#123;&#123;INSTRUCTOR&#125;&#125;'))
assert(literalXml.includes('&#123;&#123;SIGNATURE&#125;&#125;'))
if(process.argv.includes('--samples')){
  const out=new URL('../../.form-work/utilization-review/',import.meta.url)
  mkdirSync(out,{recursive:true})
  writeFileSync(new URL('standard.docx',out),fillReservationForm(template,record))
  writeFileSync(new URL('laboratory.docx',out),fillReservationForm(template,laboratoryRecord))
  writeFileSync(new URL('overflow.docx',out),long)
  writeFileSync(new URL('all-items.docx',out),fillReservationForm(template,{...record,equipment:'None',inventorySelection:JSON.stringify(structuredSelection)}))
}
